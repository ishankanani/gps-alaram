import { useState } from 'react';
import { StyleSheet, View } from 'react-native';

import { adminApi, invalidateAdmin, toAdminError, useAdminQuery } from '../../api/admin';
import type { PaidPlan, PromoCode } from '../../api/types';
import { useI18n } from '../../i18n';
import type { RootScreenProps } from '../../navigation/types';
import {
  AppText,
  Button,
  Card,
  Chip,
  ChipWrap,
  DateField,
  SegmentedControl,
  SkeletonCard,
  StickyFooter,
  SwitchRow,
  Section,
  TextField,
} from '../../ui';
import { AdminScreen, useAdminContext, withAdmin } from './components/AdminFrame';
import { errorText, useAdminAction } from './components/actions';
import { formStyles } from './components/forms';
import { ErrorState, Footnote } from './components/parts';
import { endOfLocalDay, PRESET_LABEL, PROMO_PRESET_DAYS, PROMO_PRESETS, promoPresetFor, type DurationPreset } from './lib/durations';
import { formatDate, formatNumber } from './lib/format';
import {
  checkPromoForm,
  describeGift,
  normalizePromoCode,
  parseMaxUses,
  PROMO_CODE_MAX,
  PROMO_DESCRIPTION_MAX,
  promoCreateBody,
  promoFormFrom,
  promoUpdateBody,
  type PromoForm,
} from './lib/promo';
import { PLAN_LABEL } from './lib/users';

const PLANS: PaidPlan[] = ['monthly', 'yearly', 'lifetime'];
const PROMO_CHANGED = ['promo', 'dashboard', 'audit'];

/**
 * Route `AdminPromoNew` (backend-spec 2.10 promo codes, ui-critiques "Admin: promo codes"): a new
 * code (generated by the server, or your own), or with codeId an edit of one. Plan and duration
 * lock once the code was redeemed.
 */
function AdminPromoNew({ navigation, route }: RootScreenProps<'AdminPromoNew'>) {
  const { t } = useI18n();
  const codeId = route.params?.codeId ? Number(route.params.codeId) : null;
  const query = useAdminQuery(codeId ? `promo:${codeId}` : null, () => adminApi.promoCode(codeId ?? 0));
  const title = codeId ? t('admin.promoNew.editTitle') : t('admin.promoNew.title');

  if (codeId && !query.data) {
    return (
      <AdminScreen title={title} presentation="modal" testID="screen-AdminPromoNew">
        {query.error ? (
          <ErrorState error={query.error} title={t('admin.promo.loadFailed')} onRetry={query.reload} onBack={() => navigation.goBack()} />
        ) : (
          <View style={formStyles.body}>
            <SkeletonCard />
            <SkeletonCard />
          </View>
        )}
      </AdminScreen>
    );
  }
  return <PromoEditor key={codeId ?? 'new'} existing={query.data?.promoCode ?? null} title={title} navigation={navigation} />;
}

function PromoEditor({
  existing,
  title,
  navigation,
}: {
  existing: PromoCode | null;
  title: string;
  navigation: RootScreenProps<'AdminPromoNew'>['navigation'];
}) {
  const { t } = useI18n();
  const act = useAdminAction();
  const { offline } = useAdminContext();
  const [form, setForm] = useState<PromoForm>(() => promoFormFrom(existing));
  const [custom, setCustom] = useState(false);
  const [preset, setPreset] = useState<DurationPreset>(() => promoPresetFor(existing ? existing.durationDays : 30));
  const [daysText, setDaysText] = useState(existing?.durationDays ? String(existing.durationDays) : '');
  const [tried, setTried] = useState(false);
  const [serverError, setServerError] = useState<{ field: string; text: string } | null>(null);
  const locked = !!existing && existing.redemptionCount > 0;
  const set = (patch: Partial<PromoForm>) => {
    setForm((f) => ({ ...f, ...patch }));
    setServerError(null);
  };

  const errors = checkPromoForm(form, existing);
  const valid = Object.keys(errors).length === 0;
  const code = normalizePromoCode(form.code);
  const max = parseMaxUses(form.maxRedemptions);
  const shown = (field: keyof typeof errors) => (tried && errors[field] ? t(errors[field]!) : serverError?.field === field ? serverError.text : null);

  const choosePlan = (plan: PaidPlan) => {
    if (plan === 'lifetime') set({ plan, durationDays: null });
    else if (form.plan === 'lifetime') {
      setPreset(plan === 'yearly' ? '1y' : '1m');
      set({ plan, durationDays: plan === 'yearly' ? 365 : 30 });
    } else set({ plan });
  };
  const choosePreset = (p: DurationPreset) => {
    setPreset(p);
    if (p === 'custom') set({ durationDays: Number(daysText) || null });
    else {
      // A year suggests Yearly; going shorter from Yearly suggests Monthly. The plan stays editable.
      const plan: PaidPlan = p === '1y' ? 'yearly' : form.plan === 'yearly' ? 'monthly' : form.plan;
      set({ durationDays: PROMO_PRESET_DAYS[p] ?? 30, plan });
    }
  };

  const gift = describeGift(form.plan, form.plan === 'lifetime' ? null : form.durationDays, t);
  const previewParts = [
    t('admin.promoNew.previewGives', { code: existing ? existing.code : code || t('admin.promoNew.generatedName'), gift }),
    max === null || max === 'invalid' ? t('admin.promoNew.previewAnyone') : t('admin.promoNew.previewUpTo', { count: formatNumber(max) }),
    form.startsAt ? t('admin.promoNew.previewFrom', { date: formatDate(form.startsAt) }) : null,
    form.expiresAt ? t('admin.promoNew.previewUntil', { date: formatDate(form.expiresAt) }) : null,
    form.active ? null : t('admin.promoNew.previewOff'),
  ].filter(Boolean);

  const save = () => {
    setTried(true);
    if (!valid) return;
    const body = existing ? promoUpdateBody(form, existing) : promoCreateBody(custom ? form : { ...form, code: '' });
    if (existing && Object.keys(body).length === 0) {
      navigation.goBack();
      return;
    }
    void act({
      title: existing ? t('admin.promoNew.confirmEdit', { code: existing.code }) : t('admin.promoNew.confirmCreate'),
      message: previewParts.join(' · '),
      confirmLabel: existing ? t('admin.common.save') : t('admin.promoNew.create'),
      icon: 'ticket-percent-outline',
      run: async () => {
        try {
          return existing ? await adminApi.updatePromo(existing.id, body) : await adminApi.createPromo(body as Parameters<typeof adminApi.createPromo>[0]);
        } catch (e) {
          const err = toAdminError(e);
          if (err.code === 'code_taken') setServerError({ field: 'code', text: t('admin.error.codeTaken') });
          else if (err.fields) {
            const field = Object.keys(err.fields)[0];
            if (field) setServerError({ field, text: errorText(err, t) });
          }
          throw err;
        }
      },
      success: (r) => (existing ? t('admin.promoNew.saved', { code: r.promoCode.code }) : t('admin.promoNew.created', { code: r.promoCode.code })),
      after: (r) => {
        invalidateAdmin(...PROMO_CHANGED);
        if (existing) navigation.goBack();
        else navigation.replace('AdminPromoCode', { codeId: String(r.promoCode.id) });
      },
    });
  };

  return (
    <AdminScreen
      title={title}
      presentation="modal"
      keyboard
      footer={
        <StickyFooter>
          <Button label={existing ? t('admin.edit.save') : t('admin.promoNew.create')} icon={existing ? undefined : 'plus'} size="L" block onPress={save} disabled={offline || (tried && !valid)} testID="admin-promo-save" />
        </StickyFooter>
      }
      testID="screen-AdminPromoNew">
      <View style={formStyles.body}>
        {existing ? (
          <View style={formStyles.block}>
            <AppText variant="labelM" color="textSecondary">
              {t('admin.promoNew.code')}
            </AppText>
            <AppText variant="numM" selectable>
              {existing.code}
            </AppText>
            <AppText variant="bodyS" color="textTertiary">
              {t('admin.promoNew.codeFixed')}
            </AppText>
          </View>
        ) : (
          <View style={formStyles.block}>
            <AppText variant="labelM" color="textSecondary">
              {t('admin.promoNew.code')}
            </AppText>
            <SegmentedControl
              options={[
                { value: false, label: t('admin.promoNew.generate'), icon: 'auto-fix' },
                { value: true, label: t('admin.promoNew.custom'), icon: 'pencil-outline' },
              ]}
              value={custom}
              onChange={setCustom}
              accessibilityLabel={t('admin.promoNew.code')}
              testID="admin-promo-code-mode"
            />
            {custom ? (
              <TextField
                value={form.code}
                onChangeText={(text) => set({ code: text.toUpperCase() })}
                placeholder={t('admin.promoNew.codePlaceholder')}
                autoCapitalize="characters"
                maxLength={PROMO_CODE_MAX + 8}
                helper={code && code !== form.code.trim() ? t('admin.promoNew.codeSaved', { code }) : t('admin.promoNew.codeRules')}
                error={shown('code')}
                testID="admin-promo-code-input"
              />
            ) : (
              <AppText variant="bodyS" color="textSecondary">
                {t('admin.promoNew.generateHelp')}
              </AppText>
            )}
          </View>
        )}

        <View style={formStyles.block}>
          <AppText variant="labelM" color="textSecondary">
            {t('admin.form.plan')}
          </AppText>
          <SegmentedControl
            options={PLANS.map((p) => ({ value: p, label: t(PLAN_LABEL[p]) }))}
            value={form.plan}
            onChange={locked ? () => {} : choosePlan}
            accessibilityLabel={t('admin.form.plan')}
          />
        </View>

        {form.plan !== 'lifetime' ? (
          <View style={formStyles.block}>
            <AppText variant="labelM" color="textSecondary">
              {t('admin.promoNew.gives')}
            </AppText>
            <ChipWrap radio accessibilityLabel={t('admin.promoNew.gives')}>
              {PROMO_PRESETS.map((p) => (
                <Chip
                  key={p}
                  label={p === 'custom' ? t('admin.promoNew.customDays') : t(PRESET_LABEL[p])}
                  selected={preset === p}
                  onPress={() => choosePreset(p)}
                  disabled={locked}
                />
              ))}
            </ChipWrap>
            {preset === 'custom' ? (
              <TextField
                label={t('admin.promoNew.days')}
                value={daysText}
                onChangeText={(text) => {
                  const digits = text.replace(/\D/g, '').slice(0, 4);
                  setDaysText(digits);
                  set({ durationDays: digits ? Number(digits) : null });
                }}
                variant="number"
                unit={t('admin.promoNew.daysUnit')}
                disabled={locked}
                error={shown('durationDays')}
              />
            ) : shown('durationDays') ? (
              <AppText variant="bodyS" color="danger">
                {shown('durationDays')}
              </AppText>
            ) : null}
          </View>
        ) : null}
        {locked ? <Footnote style={styles.flushNote}>{t('admin.promoNew.locked')}</Footnote> : null}

        <TextField
          label={t('admin.promoNew.maxUses')}
          value={form.maxRedemptions}
          onChangeText={(text) => set({ maxRedemptions: text.replace(/[^\d]/g, '').slice(0, 7) })}
          variant="number"
          placeholder={t('admin.promoNew.unlimited')}
          helper={existing && existing.redemptionCount > 0 ? t('admin.promoNew.maxUsesUsed', { count: formatNumber(existing.redemptionCount) }) : t('admin.promoNew.maxUsesHelp')}
          error={shown('maxRedemptions')}
          clearable
        />

        <View style={formStyles.block}>
          <DateField
            label={t('admin.promoNew.validFrom')}
            value={form.startsAt}
            onChange={(d) => set({ startsAt: d })}
            helper={form.startsAt ? formatDate(form.startsAt, { weekday: true }) : t('admin.promoNew.fromNow')}
          />
          {form.startsAt ? <Button label={t('admin.promoNew.clearFrom')} variant="ghost" size="S" onPress={() => set({ startsAt: null })} style={styles.left} /> : null}
          <DateField
            label={t('admin.promoNew.validUntil')}
            value={form.expiresAt}
            onChange={(d) => set({ expiresAt: d ? endOfLocalDay(d) : null })}
            helper={form.expiresAt ? t('admin.promoNew.untilEnd', { date: formatDate(form.expiresAt, { weekday: true }) }) : t('admin.promoNew.noEnd')}
            error={shown('expiresAt')}
          />
          {form.expiresAt ? <Button label={t('admin.promoNew.clearUntil')} variant="ghost" size="S" onPress={() => set({ expiresAt: null })} style={styles.left} /> : null}
        </View>

        <TextField
          label={t('admin.promoNew.description')}
          value={form.description}
          onChangeText={(description) => set({ description })}
          variant="multiline"
          maxLength={PROMO_DESCRIPTION_MAX}
          placeholder={t('admin.promoNew.descriptionPlaceholder')}
          error={shown('description')}
        />

        <Section style={styles.flush}>
          <SwitchRow title={t('admin.promoNew.active')} subtitle={t('admin.promoNew.activeHelp')} value={form.active} onValueChange={(active) => set({ active })} />
        </Section>

        <Card title={t('admin.promoNew.preview')}>
          <AppText variant="bodyM">{previewParts.join(' · ')}</AppText>
          <AppText variant="bodyS" color="textTertiary">
            {t('admin.promo.rule')}
          </AppText>
        </Card>
      </View>
    </AdminScreen>
  );
}

export const AdminPromoNewScreen = withAdmin(AdminPromoNew);

const styles = StyleSheet.create({
  flush: { marginHorizontal: -16 },
  flushNote: { paddingHorizontal: 0, marginTop: -16 },
  left: { alignSelf: 'flex-start', marginTop: -8 },
});
