// Writes modules/trip-alarm/ios/Support/NativeStrings.swift, the iOS module's notification texts, from
// modules/trip-alarm/shared/native-strings.json (exported from the Android L10n.kt tables by
// tools/export-native-strings.mjs). L10n.kt stays the one place to edit native texts:
//
//   node tools/export-native-strings.mjs && node modules/trip-alarm/tools/gen-ios-strings.mjs
//
// With --check it writes nothing and fails when NativeStrings.swift is out of date (iOS CI runs it).
import { readFileSync, writeFileSync } from 'node:fs';
import { argv, exit } from 'node:process';

const json = 'modules/trip-alarm/shared/native-strings.json';
const kotlin = 'modules/trip-alarm/android/src/main/java/com/ishankanani/gpsalarm/tripalarm/L10n.kt';
const target = 'modules/trip-alarm/ios/Support/NativeStrings.swift';

const { languages } = JSON.parse(readFileSync(json, 'utf8'));
const kt = readFileSync(kotlin, 'utf8');

/** A `setOf("a", "b")` from L10n.kt, so separators and text direction follow Android. */
function kotlinSet(name) {
  const match = kt.match(new RegExp(`val ${name} = setOf\\(([^)]*)\\)`));
  return match ? [...match[1].matchAll(/"(\w+)"/g)].map((m) => m[1]) : [];
}

/** A Swift string literal: escapes backslashes, quotes and control characters. */
function swiftString(text) {
  let out = '';
  for (const ch of text) {
    const code = ch.codePointAt(0);
    if (ch === '\\') out += '\\\\';
    else if (ch === '"') out += '\\"';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else if (code < 0x20) out += `\\u{${code.toString(16)}}`;
    else out += ch;
  }
  return `"${out}"`;
}

const codes = Object.keys(languages);
if (!codes.includes('en')) throw new Error(`${json} has no English table`);
const ident = (code) => `lang_${code.replace(/[^a-zA-Z0-9]/g, '_')}`;

const lines = [
  '// Generated by modules/trip-alarm/tools/gen-ios-strings.mjs from shared/native-strings.json',
  '// (which comes from android/.../L10n.kt). Do not edit by hand; edit L10n.kt and re-run both generators.',
  '',
  '// swiftlint:disable all',
  'enum NativeStrings {',
  `  static let decimalComma: Set<String> = [${kotlinSet('DECIMAL_COMMA').map(swiftString).join(', ')}]`,
  `  static let rightToLeft: Set<String> = [${kotlinSet('RTL').map(swiftString).join(', ')}]`,
  '',
  `  static let tables: [String: [String: String]] = [${codes.map((c) => `${swiftString(c)}: ${ident(c)}`).join(', ')}]`,
];
for (const code of codes) {
  lines.push('', `  private static let ${ident(code)}: [String: String] = [`);
  for (const [key, text] of Object.entries(languages[code])) lines.push(`    ${swiftString(key)}: ${swiftString(text)},`);
  lines.push('  ]');
}
lines.push('}', '');
const swift = lines.join('\n');

if (argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // Missing counts as out of date.
  }
  if (current !== swift) {
    console.error(`${target} is out of date: run node modules/trip-alarm/tools/gen-ios-strings.mjs`);
    exit(1);
  }
  console.log(`${target} is up to date (${codes.length} languages)`);
} else {
  writeFileSync(target, swift);
  console.log(`${codes.length} languages -> ${target}`);
}
