/**
 * Helpers shared by the route modules: response shapes built from rows, and small validators.
 */
import type { AuthResponse, MeResponse, PlanResponse } from '../../../src/api/types.ts';
import type { RequestContext } from '../context.ts';
import { planResponse } from '../domain/plans.ts';
import { toSession, type SessionRow } from '../domain/sessions.ts';
import { getUser, toUser, type UserRow } from '../domain/users.ts';
import { INSTALL_ID_RE } from '../domain/ids.ts';
import { unauthorized } from '../http/errors.ts';
import { hasOwn, type Body, type Fields } from '../http/validate.ts';

export function planOf(ctx: RequestContext, user: UserRow): PlanResponse {
  return planResponse(ctx.app.db, user, ctx.now, ctx.app.planView());
}

export function meResponse(ctx: RequestContext, user: UserRow, session: SessionRow): MeResponse {
  return { ...planOf(ctx, user), user: toUser(user), session: toSession(session) };
}

export function authResponse(ctx: RequestContext, user: UserRow, session: SessionRow, token: string): AuthResponse {
  return { ...meResponse(ctx, user, session), token };
}

/** The current row of a user that must still exist (the session's user may have been deleted meanwhile). */
export function reloadUser(ctx: RequestContext, userId: string): UserRow {
  const u = getUser(ctx.app.db, userId);
  if (!u) throw unauthorized();
  return u;
}

/** installId: a lowercase UUID v4 generated by the app per installation. */
export function readInstallId(v: Fields, body: Body, key = 'installId'): string {
  if (!hasOwn(body, key)) {
    v.add(key, 'required');
    return '';
  }
  const value = body[key];
  if (typeof value !== 'string' || !INSTALL_ID_RE.test(value)) {
    v.add(key, 'invalid');
    return '';
  }
  return value;
}
